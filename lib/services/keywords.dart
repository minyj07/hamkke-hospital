/// 한 글자 키워드 뒤에 붙어도 되는 조사.
const _particles = '이가은는을를에도와과랑만';

/// 입력한 글에 들어 있는 진료과 이름(예: 피부과)과 키워드로 진료과를 찾는다.
Set<String> departmentsFromText(String text, Iterable<String> departmentNames) {
  final lower = text.toLowerCase();
  final joined = lower.replaceAll(RegExp(r'\s+'), '');
  if (joined.isEmpty) return {};
  final words = lower.split(RegExp(r'[\s,./·]+'));

  // 한 글자 키워드(눈·귀·코·폐·뼈)는 '희귀질환', '폐경'처럼 다른 낱말 속에 든 경우를 빼고
  // 낱말 그대로이거나 조사가 붙은 경우(귀가, 눈이)만 본다.
  bool mentions(String key) => key.length > 1
      ? joined.contains(key)
      : words.any((w) =>
          w == key ||
          (w.length == 2 && w.startsWith(key) && _particles.contains(w[1])));

  final named = [
    for (final name in departmentNames)
      if (joined.contains(name)) name,
  ];
  return {
    // '정형외과'라고 쓰면 그 안의 '외과'는 따로 찾지 않는다.
    for (final name in named)
      if (!named.any((other) => other != name && other.contains(name))) name,
    for (final MapEntry(:key, :value) in _keywordDepartments.entries)
      if (mentions(key)) ...value,
  };
}
